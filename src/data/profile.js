// ---------- Date helpers ----------

const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

function parseYM(ym) {
  const [y, m] = ym.split("-").map(Number);
  return { y, m };
}

export function formatMonth(ym) {
  if (!ym) return "Present";
  const { y, m } = parseYM(ym);
  return `${MONTHS[m - 1]} ${y}`;
}

// Inclusive month count, matching how LinkedIn reports durations (May–Sep = 5 mos).
export function durationLabel(start, end, now = new Date()) {
  const s = parseYM(start);
  const e = end ? parseYM(end) : { y: now.getFullYear(), m: now.getMonth() + 1 };
  const total = Math.max(1, (e.y - s.y) * 12 + (e.m - s.m) + 1);
  const years = Math.floor(total / 12);
  const months = total % 12;
  const parts = [];
  if (years) parts.push(`${years} yr${years > 1 ? "s" : ""}`);
  if (months) parts.push(`${months} mo${months > 1 ? "s" : ""}`);
  return parts.join(" ");
}

// A role counts as current until its end month is over
export function isCurrent(job, now = new Date()) {
  if (!job.end) return true;
  const { y, m } = parseYM(job.end);
  return now.getFullYear() * 12 + now.getMonth() + 1 <= y * 12 + m;
}

export function dateRange(job) {
  return `${formatMonth(job.start)} – ${formatMonth(job.end)}`;
}

